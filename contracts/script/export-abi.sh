#!/usr/bin/env bash
set -euo pipefail
contracts_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
workspace_dir="$(cd -- "$contracts_dir/.." && pwd)"
cd "$contracts_dir"
bin/forge.sh build
sudo docker run --rm --user "$(id -u):$(id -g)" \
  -v "$workspace_dir:/workspace" -w /workspace --entrypoint node node:22-alpine \
  --input-type=module -e '
import fs from "node:fs";
import prettier from "./www/node_modules/prettier/index.mjs";
const { abi } = JSON.parse(fs.readFileSync("contracts/out/PingRouter.sol/PingRouter.json", "utf8"));
const source = "// Generated by contracts/script/export-abi.sh.\nexport const pingRouterAbi = " + JSON.stringify(abi, null, 2) + " as const;\n";
for (const target of ["src/lib/pingRouterAbi.ts", "www/src/wallet/pingRouterAbi.ts"]) {
  const output = target.startsWith("www/")
    ? await prettier.format(source, { ...await prettier.resolveConfig(target), filepath: target })
    : source;
  fs.writeFileSync(target, output);
  console.log(`Exported ${target}`);
}
'
